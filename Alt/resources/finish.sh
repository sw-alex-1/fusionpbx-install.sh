#!/bin/sh

# FusionPBX Alt Linux Installer - Finish
# Final step: database schema, admin user, service configuration, and startup.
#
# This script matches the Debian installer's finish.sh flow.
# FreeSWITCH is already running (started by package-systemd.sh in switch.sh)
# which means upgrade.php --defaults can access the event socket and populate
# switch settings correctly — including v_music_on_hold.
#
# Alt Linux specifics:
#   - Web user: _nginx:_nginx (NOT www-data:www-data)
#   - FreeSWITCH user: _nginx:_nginx (same as web user, like Debian's www-data)
#   - hostname -I not supported — use 'ip addr' instead
#   - tmpfiles.d for /var/run/fusionpbx persistence across reboots
#   - upgrade.php --permissions uses 'www-data' — must do manual chown instead
#   - PHP CLI must have pdo_pgsql loaded for FusionPBX DB access

# Determine script directory
SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
cd "$SCRIPT_DIR"

# Includes
. "$SCRIPT_DIR/config.sh"
. "$SCRIPT_DIR/colors.sh"
. "$SCRIPT_DIR/util.sh"
. "$SCRIPT_DIR/environment.sh"

# =============================================================================
# Database password
# Retrieve the password generated by postgresql.sh (stored in /tmp).
# If not available (standalone run), generate a new one.
# =============================================================================

_pg_cred_file="/tmp/fusionpbx_db_credentials"

if [ -f "$_pg_cred_file" ]; then
    # Read the password saved by postgresql.sh
    . "$_pg_cred_file"
    verbose "Retrieved database password from postgresql.sh"
elif [ ."${database_password}" = ."random" ] || [ -z "$database_password" ]; then
    # Standalone run or postgresql.sh didn't save credentials
    database_password=$(dd if=/dev/urandom bs=1 count=20 2>/dev/null | base64 | sed 's/[=\+//]//g')
    verbose "Generated new random database password"
fi

# Set PGPASSWORD for psql commands in this script
export PGPASSWORD=$database_password

# =============================================================================
# Update the database password
# =============================================================================

verbose "Setting database passwords..."

# Update fusionpbx user password
# Force md5 encryption to match pg_hba.conf auth method (see postgresql.sh)
runuser -u postgres -- psql -c "SET password_encryption = 'md5'; ALTER USER fusionpbx WITH PASSWORD '$database_password';" || die "Failed to update fusionpbx database password"

# Also create/update freeswitch role (required by FusionPBX internals)
if runuser -u postgres -- psql -tAc "SELECT 1 FROM pg_roles WHERE rolname='freeswitch'" 2>/dev/null | grep -q 1; then
    runuser -u postgres -- psql -c "SET password_encryption = 'md5'; ALTER USER freeswitch WITH PASSWORD '$database_password';" 2>/dev/null
    verbose "  freeswitch role password updated"
else
    runuser -u postgres -- psql -c "SET password_encryption = 'md5'; CREATE ROLE freeswitch WITH SUPERUSER LOGIN PASSWORD '$database_password';" 2>/dev/null
    verbose "  freeswitch role created"
fi

# =============================================================================
# Install backup/maintenance cron scripts
# =============================================================================

verbose "Installing backup and maintenance scripts..."

# Copy backup scripts to cron.daily
cp "$SCRIPT_DIR/backup/fusionpbx-backup" /etc/cron.daily/fusionpbx-backup
cp "$SCRIPT_DIR/backup/fusionpbx-maintenance" /etc/cron.daily/fusionpbx-maintenance
chmod 755 /etc/cron.daily/fusionpbx-backup
chmod 755 /etc/cron.daily/fusionpbx-maintenance

# Replace the password placeholder in backup scripts
sed -i "s/zzz/$database_password/g" /etc/cron.daily/fusionpbx-backup
sed -i "s/zzz/$database_password/g" /etc/cron.daily/fusionpbx-maintenance

# =============================================================================
# FusionPBX configuration
# Deploy config.conf to /etc/fusionpbx/
# =============================================================================

verbose "Configuring FusionPBX..."

# Deploy to /etc/fusionpbx/config.conf (primary location)
ensure_dir "/etc/fusionpbx"
cp "$SCRIPT_DIR/fusionpbx/config.conf" /etc/fusionpbx/config.conf

# Replace placeholders with actual values
sed -i /etc/fusionpbx/config.conf -e s:"{database_host}:$database_host:"
sed -i /etc/fusionpbx/config.conf -e s:"{database_name}:$database_name:"
sed -i /etc/fusionpbx/config.conf -e s:"{database_username}:$database_username:"
sed -i /etc/fusionpbx/config.conf -e s:"{database_password}:$database_password:"

# Also update the resources/ fallback config with real values
_fpbx_res_config="/var/www/fusionpbx/resources/config.conf"
if [ -f "$_fpbx_res_config" ]; then
    sed -i "$_fpbx_res_config" -e s:"{database_host}:$database_host:"
    sed -i "$_fpbx_res_config" -e s:"{database_name}:$database_name:"
    sed -i "$_fpbx_res_config" -e s:"{database_username}:$database_username:"
    sed -i "$_fpbx_res_config" -e s:"{database_password}:$database_password:"
    verbose "  resources/config.conf also updated with database credentials"
fi

# =============================================================================
# Verify PHP can connect to PostgreSQL via PDO
# This is critical — if PDO connection fails, ALL FusionPBX PHP scripts will fail.
# =============================================================================

verbose "Verifying PHP PDO connection to PostgreSQL..."

_php_cmd="php${php_version}"
if ! command -v "$_php_cmd" >/dev/null 2>&1; then
    _php_cmd="php"
fi

# Check if pdo_pgsql extension is loaded
_pdo_pgsql_status=$("$_php_cmd" -m 2>/dev/null | grep -i 'pdo_pgsql')
if [ -z "$_pdo_pgsql_status" ]; then
    error "CRITICAL: PHP pdo_pgsql extension is NOT loaded!"
    error "Installed PHP modules:"
    "$_php_cmd" -m 2>/dev/null | grep -iE 'pdo|pgsql' || error "  (none found)"
    error "Attempting to install missing PDO PostgreSQL extension..."
    pkg_install "php${php_version}-pdo_pgsql" 2>/dev/null || \
        warn "php${php_version}-pdo_pgsql package not found"
    # Reload after install
    _pdo_pgsql_status=$("$_php_cmd" -m 2>/dev/null | grep -i 'pdo_pgsql')
    if [ -z "$_pdo_pgsql_status" ]; then
        die "Cannot proceed without pdo_pgsql. Install it manually: apt-get install php${php_version}-pdo_pgsql"
    fi
fi
verbose "  pdo_pgsql extension: loaded"

# Test actual PDO connection
_pdo_test=$("$_php_cmd" -r "
try {
    \$pdo = new PDO('pgsql:host=$database_host;port=$database_port;dbname=$database_name', '$database_username', '$database_password');
    echo 'OK';
} catch (Exception \$e) {
    echo 'FAILED: ' . \$e->getMessage();
}
" 2>&1)

if echo "$_pdo_test" | grep -q "^OK"; then
    verbose "  PDO connection to PostgreSQL: successful"
else
    die "PDO connection test FAILED: $_pdo_test — PHP cannot connect to PostgreSQL via PDO. The installer cannot continue."
fi

# =============================================================================
# Database schema
# =============================================================================

verbose "Installing database schema..."

cd /var/www/fusionpbx && /usr/bin/php /var/www/fusionpbx/core/upgrade/upgrade.php --schema \
    || die "upgrade.php --schema failed. Check database connectivity and PHP configuration."

# =============================================================================
# Domain configuration
# =============================================================================

#get the server hostname
if [ ."${domain_name}" = ."hostname" ]; then
    domain_name=$(hostname -f)
fi

#get the ip address — Alt Linux hostname does NOT support -I flag
# Use 'ip addr' instead, which is universally available
if [ ."${domain_name}" = ."ip_address" ]; then
    domain_name=$(ip -4 addr show scope global | grep inet | head -1 | awk '{print $2}' | cut -d'/' -f1)
    # Fallback: try hostname -i (works on some systems)
    if [ -z "$domain_name" ]; then
        domain_name=$(hostname -i 2>/dev/null | cut -d' ' -f1)
    fi
    # Last fallback: try /sbin/ifconfig
    if [ -z "$domain_name" ]; then
        domain_name=$(/sbin/ifconfig 2>/dev/null | grep 'inet ' | grep -v '127.0.0.1' | head -1 | awk '{print $2}' | sed 's/addr://')
    fi
fi

verbose "Domain: $domain_name"

#get the domain_uuid
domain_uuid=$(/usr/bin/php /var/www/fusionpbx/resources/uuid.php) || die "Failed to generate domain UUID"

#add the domain name
psql --host=$database_host --port=$database_port --username=$database_username -c \
    "insert into v_domains (domain_uuid, domain_name, domain_enabled) values('$domain_uuid', '$domain_name', 'true');" \
    || die "Failed to insert domain into v_domains"

# =============================================================================
# App defaults (1st run)
# FreeSWITCH is already running, so event socket is available.
# This means switch settings will be populated correctly.
# =============================================================================

verbose "Running app defaults (1st run)..."

cd /var/www/fusionpbx && /usr/bin/php /var/www/fusionpbx/core/upgrade/upgrade.php --defaults \
    || die "upgrade.php --defaults (1st run) failed. Check PHP and database connectivity."

# =============================================================================
# Admin user
# =============================================================================

verbose "Creating admin user..."

user_uuid=$(/usr/bin/php /var/www/fusionpbx/resources/uuid.php) || die "Failed to generate user UUID"
user_salt=$(/usr/bin/php /var/www/fusionpbx/resources/uuid.php) || die "Failed to generate user salt"
user_name=$system_username

if [ ."${system_password}" = ."random" ]; then
    user_password=$(dd if=/dev/urandom bs=1 count=20 2>/dev/null | base64 | sed 's/[=\+//]//g')
else
    user_password=$system_password
fi

password_hash=$(/usr/bin/php -r "echo md5('$user_salt$user_password');")

psql --host=$database_host --port=$database_port --username=$database_username -t -c \
    "insert into v_users (user_uuid, domain_uuid, username, password, salt, user_enabled) \
     values('$user_uuid', '$domain_uuid', '$user_name', '$password_hash', '$user_salt', 'true');"

#get the superadmin group_uuid
group_uuid=$(psql --host=$database_host --port=$database_port --username=$database_username -qtAX -c \
    "select group_uuid from v_groups where group_name = 'superadmin';")

#add the user to the group
user_group_uuid=$(/usr/bin/php /var/www/fusionpbx/resources/uuid.php)
group_name=superadmin

psql --host=$database_host --port=$database_port --username=$database_username -c \
    "insert into v_user_groups (user_group_uuid, domain_uuid, group_name, group_uuid, user_uuid) \
     values('$user_group_uuid', '$domain_uuid', '$group_name', '$group_uuid', '$user_uuid');"

# =============================================================================
# XML CDR configuration
# =============================================================================

verbose "Configuring XML CDR..."

xml_cdr_username=$(dd if=/dev/urandom bs=1 count=20 2>/dev/null | base64 | sed 's/[=\+//]//g')
xml_cdr_password=$(dd if=/dev/urandom bs=1 count=20 2>/dev/null | base64 | sed 's/[=\+//]//g')

sed -i /etc/freeswitch/autoload_configs/xml_cdr.conf.xml -e s:"{v_http_protocol}:http:"
sed -i /etc/freeswitch/autoload_configs/xml_cdr.conf.xml -e s:"{domain_name}:$database_host:"
sed -i /etc/freeswitch/autoload_configs/xml_cdr.conf.xml -e s:"{v_project_path}::"
sed -i /etc/freeswitch/autoload_configs/xml_cdr.conf.xml -e s:"{v_user}:$xml_cdr_username:"
sed -i /etc/freeswitch/autoload_configs/xml_cdr.conf.xml -e s:"{v_pass}:$xml_cdr_password:"

# =============================================================================
# Update app defaults (2nd run)
# Matches Debian: runs upgrade.php --defaults a second time after
# domain, user, and xml_cdr are configured.
# =============================================================================

verbose "Updating app defaults (2nd run)..."

cd /var/www/fusionpbx && /usr/bin/php /var/www/fusionpbx/core/upgrade/upgrade.php --defaults \
    || die "upgrade.php --defaults (2nd run) failed. Check PHP and database connectivity."

# =============================================================================
# Verify v_music_on_hold was populated
# If FreeSWITCH is running and app_defaults worked correctly, v_music_on_hold
# should have entries. If it's still empty (edge case), the fallback script
# will insert default entries via SQL.
# =============================================================================

verbose "Verifying music on hold configuration..."
"$SCRIPT_DIR/switch/music-on-hold.sh" || die "Music on hold configuration failed"

# =============================================================================
# Set file permissions manually
# FusionPBX's upgrade.php --permissions uses 'www-data' which doesn't exist
# on Alt Linux. We do manual chown with the correct web user instead.
# =============================================================================

verbose "Setting file permissions..."

# Set ownership for FusionPBX web files
chown -R ${web_user}:${web_group} /var/www/fusionpbx

# Set ownership for FreeSWITCH scripts dir
# Both web user and FreeSWITCH need access (they're the same user now)
if [ -d /usr/share/freeswitch/scripts ]; then
    chown -R ${web_user}:${web_group} /usr/share/freeswitch/scripts
fi

# Config file permissions
chmod 664 /etc/fusionpbx/config.conf
chown ${web_user}:${web_group} /etc/fusionpbx/config.conf

verbose "  File permissions set (owner: ${web_user}:${web_group})"

# =============================================================================
# /var/run/fusionpbx persistence
# =============================================================================

verbose "Configuring /var/run/fusionpbx persistence..."

mkdir -p /var/run/fusionpbx
chown -R ${web_user}:${web_group} /var/run/fusionpbx

# Create tmpfiles.d configuration so systemd-tmpfiles recreates this on boot
cat > /etc/tmpfiles.d/fusionpbx.conf << EOF
# FusionPBX runtime directory — recreated on boot by systemd-tmpfiles
d /var/run/fusionpbx 0775 ${web_user} ${web_group} -
EOF

verbose "  Created /etc/tmpfiles.d/fusionpbx.conf"

# =============================================================================
# Restart FreeSWITCH (matches Debian)
# After --defaults and --permissions, restart FreeSWITCH so it picks up
# all the configuration changes made by upgrade.php.
# =============================================================================

verbose "Restarting FreeSWITCH..."
systemctl restart freeswitch || warn "FreeSWITCH restart failed"

# =============================================================================
# Install cron (required for FusionPBX scheduled tasks and cron.daily scripts)
# =============================================================================

verbose "Installing cron daemon..."
pkg_install cron
systemctl enable crond 2>/dev/null || systemctl enable cron 2>/dev/null || warn "Failed to enable cron service"
systemctl start crond 2>/dev/null || systemctl start cron 2>/dev/null || warn "Failed to start cron service"
verbose "  Cron daemon installed and started"

# =============================================================================
# Install FusionPBX services
# upgrade.php --services creates systemd service files or cron entries
# for FusionPBX background services (xml_cdr, email_queue, fax_queue, etc.)
# IMPORTANT: The generated files may reference 'www-data' which doesn't exist
# on Alt Linux. We patch them after creation.
# =============================================================================

verbose "Installing FusionPBX services..."

cd /var/www/fusionpbx && /usr/bin/php /var/www/fusionpbx/core/upgrade/upgrade.php --services || \
    warn "FusionPBX services installation had errors (some services may need manual setup)"

# Patch any generated service files that reference www-data (doesn't exist on Alt Linux)
verbose "Patching FusionPBX service files for Alt Linux user (${web_user})..."
for _svc_file in /etc/systemd/system/fusionpbx*.service /lib/systemd/system/fusionpbx*.service; do
    if [ -f "$_svc_file" ]; then
        sed -i "s/www-data/${web_user}/g" "$_svc_file"
        sed -i "s/User=www-data/User=${web_user}/g" "$_svc_file"
        sed -i "s/Group=www-data/Group=${web_group}/g" "$_svc_file"
        verbose "  Patched: $_svc_file"
    fi
done
# Also patch any cron files that may reference www-data
for _cron_file in /etc/cron.d/fusionpbx*; do
    if [ -f "$_cron_file" ]; then
        sed -i "s/www-data/${web_user}/g" "$_cron_file"
        verbose "  Patched: $_cron_file"
    fi
done
systemctl daemon-reload

# =============================================================================
# Enable all services for auto-start on boot
# =============================================================================

verbose "Enabling services for auto-start on boot..."

for _svc in nginx "php${php_version}-fpm" postgresql freeswitch memcached; do
    if systemctl is-enabled "$_svc" 2>/dev/null; then
        verbose "  $_svc: already enabled"
    else
        systemctl enable "$_svc" 2>/dev/null && verbose "  $_svc: enabled" || warn "  $_svc: failed to enable"
    fi
done

# =============================================================================
# Final restart of nginx and FreeSWITCH (matches Debian)
# After services are installed and all configuration is complete,
# do a final restart of both nginx and FreeSWITCH.
# =============================================================================

verbose "Final restart of nginx and FreeSWITCH..."
systemctl restart nginx freeswitch || warn "nginx/FreeSWITCH restart had issues"
verbose "  nginx and FreeSWITCH restarted"

# =============================================================================
# Welcome message
# =============================================================================

echo ""
echo ""
verbose "Installation Complete!"
echo ""
echo "   Please save this information and reboot this system to complete the install."
echo ""
echo "   Use a web browser to login."
echo "      domain name: https://$domain_name"
echo "      username:    $user_name"
echo "      password:    $user_password"
echo ""
echo "   The domain name in the browser is used by default as part of the authentication."
echo "   If you need to login to a different domain then use username@domain."
echo "      username: $user_name@$domain_name"
echo ""
echo "   Official FusionPBX Training"
echo "      Fastest way to learn FusionPBX. For more information https://www.fusionpbx.com."
echo "      Available online and in person. Includes documentation and recording."
echo ""
echo "      Location:               Online"
echo "      Admin Training:          TBA"
echo "      Advanced Training:       TBA"
echo "      Continuing Education:   https://www.fusionpbx.com/training"
echo "      Timezone:               https://www.timeanddate.com/weather/usa/idaho"
echo ""
echo "   Additional information."
echo "      https://fusionpbx.com/members.php"
echo "      https://fusionpbx.com/training.php"
echo "      https://fusionpbx.com/support.php"
echo "      https://www.fusionpbx.com"
echo "      http://docs.fusionpbx.com"
echo ""

# =============================================================================
# Cleanup — unset PGPASSWORD for security
# =============================================================================

unset PGPASSWORD
